test('Zillow ZIP parse never invents a code and FMR compare follows visible price',()=>{
 const page=fixture('zillow-fmr');
 const facts=P.extractZillowFacts(page);
 assert.equal(facts.zip,'10001');
 assert.equal(facts.bedrooms,2);
 assert.deepEqual(facts.price,{amount:2500,period:'month'});
 assert.equal(P.parseZillow(page).length,2);
 const view=P.buildFmrView(facts,HUD);
 assert.equal(view.status,'ok');
 assert.equal(view.compare.fmr,4460);
 assert.equal(view.compare.delta,2500-4460);
 assert.match(P.fmrLines(view).join('\n'),/Rent − FMR: -\$1,960/);
 assert.equal(view.sourceUrl,HUD.meta.sourceUrl);
 const noPrice=P.buildFmrView(P.extractZillowFacts(page.replace(/<span data-testid="price">[\s\S]*?<\/span>/,'')),HUD);
 assert.equal(noPrice.status,'ok');
 assert.equal(noPrice.compare,null);
 assert.equal(P.fmrLines(noPrice).some(line=>/List price|Monthly rent|Rent − FMR/.test(line)),false);
 const hidden=P.buildFmrView(P.extractZillowFacts('<title>Home</title><h1>10 Example Ave, Springfield</h1><p>Built IN 20261</p><span data-testid="price">$500,000</span>'),HUD);
 assert.equal(hidden.status,'undetermined');
 assert.equal(hidden.message,'无法判定：页面未显示可识别的邮政编码');
 assert.equal(hidden.rows,null);
 assert.equal(hidden.compare,null);
 assert.equal(P.fmrLines(hidden).some(line=>line.includes('$')),false);
 const split=P.extractZillowFacts('<title>1 A St, New York, NY 10001</title><h1>2 B St, Beverly Hills, CA 90210</h1>');
 assert.match(split.zipError,/无法判定：页面出现多个不同邮政编码/);
 assert.equal(P.parseZip('NY 10001-1234').zip,'10001');
 assert.equal(P.parseZip('https://www.zillow.com/homedetails/350-5th-Ave-New-York-NY-10001/1_zpid/').zip,'10001');
 const sale=P.buildFmrView(P.zillowFactsFromParts({addressText:'NY 10001',priceText:'$900,000',bedText:'2 beds'}),HUD);
 assert.equal(sale.compare.delta,null);
 assert.match(P.fmrLines(sale).join('\n'),/List price: \$900,000/);
 assert.equal(P.fmrLines(sale).some(line=>line.includes('Rent − FMR')),false);
 const noBed=P.buildFmrView(P.zillowFactsFromParts({addressText:'NY 10001',priceText:'$900,000',bedText:''}),HUD);
 assert.equal(noBed.compare.bedroom,null);
 assert.equal(noBed.compare.fmr,null);
 assert.equal(P.fmrLines(noBed).some(line=>line.includes('← listing')||line.includes('BR FMR')),false);
 const studio=P.buildFmrView(P.zillowFactsFromParts({addressText:'PR 00602',bedText:'Studio',priceText:'$700/mo'}),HUD);
 assert.equal(studio.compare.bedroom,0);
 assert.equal(studio.compare.fmr,460);
 const five=P.buildFmrView(P.zillowFactsFromParts({addressText:'NY 10001',bedText:'5 beds',priceText:'$9,000/mo'}),HUD);
 assert.equal(five.compare.fmr,null);
 assert.match(five.compare.note,/0–4/);
 const ambiguous=P.buildFmrView(P.extractZillowFacts('<h1>New York, NY 10001</h1><span data-testid="price">$10</span><span data-testid="price">$20</span>'),HUD);
 assert.equal(ambiguous.status,'ok');
 assert.equal(ambiguous.compare,null);
 const missed=P.buildFmrView(P.zillowFactsFromParts({addressText:'NY 00501',priceText:'$1000/mo',bedText:'1 bed'}),HUD);
 assert.match(missed.message,/无法判定：FY 2027 HUD SAFMR 公开表无此 ZIP 00501/);
 assert.equal(missed.rows,null);
 const header=P.zillowFactsFromParts({addressText:'NY 10001',headerText:'3 beds\n$500,000\nZestimate $700,000\nSold $1'});
 assert.equal(header.bedrooms,3);
 assert.deepEqual(header.price,{amount:500000,period:'sale'});
 assert.equal(P.shouldInjectFmr('https://www.zillow.com/homedetails/350-5th-Ave-New-York-NY-10001/1_zpid/'),true);
 assert.equal(P.shouldInjectFmr('https://www.zillow.com/homes/for_sale/'),false);
 assert.equal(P.shouldInjectFmr('https://www.redfin.com/homedetails/1'),false);
 assert.equal(P.shouldInjectFmr('https://www.rightmove.co.uk/properties/1'),false);
 assert.equal(P.shouldInjectFmr('https://zillow.com/homedetails/1'),false);
});
