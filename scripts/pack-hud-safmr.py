#!/usr/bin/env python3
"""Pack a HUD USER Small Area FMR workbook into src/data/hud-fy2027-safmr.js.

The extension ships only ZIP and SAFMR 0BR–4BR. The 90% and 110% payment-standard
columns in the workbook are omitted on purpose (out of scope for this cut).

Usage:
  python3 scripts/pack-hud-safmr.py /path/to/FY27_safmrs.xlsx

Requires openpyxl. Re-run only when replacing the packed FY table, and record the
new SHA-256 plus the HTTP Last-Modified date in this script before shipping.
"""
import hashlib
import sys
from collections import defaultdict
from pathlib import Path

FY = 2027
FILE_LAST_MODIFIED = '2026-08-31'
SOURCE_URL = 'https://www.huduser.gov/portal/datasets/fmr/smallarea/index.html'
FILE_URL = 'https://www.huduser.gov/portal/datasets/fmr/fmr2027/FY27_safmrs.xlsx'
DATASETS_URL = 'https://www.huduser.gov/portal/datasets/fmr.html'
WIDTH = 26
RENT_COLUMNS = (3, 6, 9, 12, 15)
OUT = Path(__file__).resolve().parents[1] / 'src' / 'data' / 'hud-fy2027-safmr.js'
# Pins from the FY2027 workbook (and, for 35096, the public SAFMR schedule PDF).
PINS = {
    '35096': (920, 960, 1180, 1550, 1550),
    '10001': (3890, 4100, 4460, 5640, 6190),
    '90210': (3230, 3610, 4450, 5650, 6320),
    '00602': (460, 460, 560, 670, 750),
}


def load_rows(path):
    import openpyxl
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb[wb.sheetnames[0]]
    rows = ws.iter_rows(values_only=True)
    header = next(rows)
    expected = ['SAFMR\n0BR', 'SAFMR\n1BR', 'SAFMR\n2BR', 'SAFMR\n3BR', 'SAFMR\n4BR']
    for index, name in zip(RENT_COLUMNS, expected):
        if header[index] != name:
            raise SystemExit(f'unexpected column {index}: {header[index]!r}')
    grouped = defaultdict(list)
    for row in rows:
        if row[0] is None:
            continue
        zip_code = str(row[0]).strip()
        if len(zip_code) != 5 or not zip_code.isdigit():
            raise SystemExit(f'bad ZIP {row[0]!r}')
        rents = tuple(int(row[i]) for i in RENT_COLUMNS)
        if any(n < 0 or n > 9999 for n in rents):
            raise SystemExit(f'rent out of range for {zip_code}: {rents}')
        grouped[zip_code].append((rents, str(row[1] or '')))
    return grouped


def pack(grouped):
    records = []
    for zip_code in sorted(grouped):
        items = grouped[zip_code]
        rent_sets = {item[0] for item in items}
        if len(rent_sets) != 1:
            raise SystemExit(
                f'{zip_code} has disagreeing SAFMR rows; refusing to pick one: {items}'
            )
        multi = '1' if len({item[1] for item in items}) > 1 else '0'
        body = ''.join(f'{n:04d}' for n in items[0][0])
        record = zip_code + body + multi
        if len(record) != WIDTH or not record[:-1].isdigit() or record[-1] not in '01':
            raise SystemExit(f'bad record {record}')
        records.append(record)
    blob = ''.join(records)
    if len(blob) != len(records) * WIDTH:
        raise SystemExit('blob length mismatch')
    return records, blob


def lookup(blob, zip_code):
    count = len(blob) // WIDTH
    lo, hi = 0, count - 1
    while lo <= hi:
        mid = (lo + hi) // 2
        start = mid * WIDTH
        found = blob[start:start + 5]
        if found == zip_code:
            rents = tuple(int(blob[start + 5 + i * 4:start + 9 + i * 4]) for i in range(5))
            return rents, blob[start + 25] == '1'
        if found < zip_code:
            lo = mid + 1
        else:
            hi = mid - 1
    return None


def emit(blob, count, sha256):
    chunks = [blob[i:i + WIDTH * 40] for i in range(0, len(blob), WIDTH * 40)]
    body = ',\n'.join("'" + chunk + "'" for chunk in chunks)
    text = f"""/* Generated by scripts/pack-hud-safmr.py. Do not edit by hand.
   HUD USER FY{FY} Small Area FMRs, ZIP and 0BR–4BR only.
   Source page: {SOURCE_URL}
   Workbook: {FILE_URL}
   HTTP Last-Modified observed: {FILE_LAST_MODIFIED}
   SHA-256: {sha256}
   Payment-standard (90%/110%) columns are not packed. */
(function(root){{
'use strict';
const pack={{
 meta:{{
  fy:{FY},
  kind:'SAFMR',
  sourceUrl:{SOURCE_URL!r},
  fileUrl:{FILE_URL!r},
  datasetsUrl:{DATASETS_URL!r},
  fileLastModified:{FILE_LAST_MODIFIED!r},
  sha256:{sha256!r},
  note:'Packed from the public FY{FY} SAFMR workbook. Fiscal year {FY} generally begins 2026-10-01. Areas with a HUD reevaluation may still be on a prior effective schedule; the HUD USER publication controls.'
 }},
 width:{WIDTH},
 count:{count},
 blob:[{body}].join('')
}};
Object.assign(root.PropertyTools ||= {{}}, {{HUD_FMR_PACK:pack}});
if(typeof module!=='undefined'&&module.exports)module.exports=pack;
}})(globalThis);
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding='utf-8')


def main():
    if len(sys.argv) != 2:
        raise SystemExit('usage: pack-hud-safmr.py FY27_safmrs.xlsx')
    path = Path(sys.argv[1])
    sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
    grouped = load_rows(path)
    records, blob = pack(grouped)
    for zip_code, rents in PINS.items():
        found = lookup(blob, zip_code)
        if not found or found[0] != rents:
            raise SystemExit(f'pin failed for {zip_code}: {found}')
    emit(blob, len(records), sha256)
    print(f'wrote {OUT} zips={len(records)} bytes={len(blob)} sha256={sha256}')


if __name__ == '__main__':
    main()
